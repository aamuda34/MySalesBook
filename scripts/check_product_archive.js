'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const app=fs.readFileSync('app.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const migration=fs.readFileSync('supabase/migrations/20261105010100_reversible_product_archiving.sql','utf8');
const salesGuard=fs.readFileSync('supabase/migrations/20261105010200_reject_sales_for_archived_products.sql','utf8');
const start=app.indexOf('function isProductArchived(');
const end=app.indexOf('function getActiveProducts(',start);
assert.ok(start>=0&&end>start,'Could not locate the production archive status helper.');
const context={};
vm.runInNewContext(app.slice(start,end)+String.fromCharCode(10)+'globalThis.isArchived=isProductArchived;',context);
assert.equal(context.isArchived({id:'a',archivedAt:null}),false);
assert.equal(context.isArchived({id:'a',archivedAt:'2026-11-05T00:00:00Z'}),true);
assert.equal(context.isArchived({id:'a',archived_at:'2026-11-05T00:00:00Z'}),true);
assert.ok(app.includes('archived_at,created_at,updated_at'),'Cloud product refresh loads archive status.');
assert.ok(app.includes('archived_at:product.archivedAt||null'),'Product writes persist archive status.');
assert.ok(app.includes('product.archivedAt=nextArchived?now():null'),'Archive and restore use the existing recoverable product-save queue.');
assert.ok(app.includes("statusFilter?.value==='archived'?getArchivedProducts():allStatusProducts"),'Products page filters current and archived products.');
assert.ok(app.includes('getActiveProducts().map(p=>'),'New business operations select only active products.');
assert.ok(app.includes('db.stockAdjustments.some(row=>row.productId===id)||db.restocks.some(row=>row.productId===id)'),'Products with business history cannot be hard-deleted.');
assert.ok(html.includes('id="productStatusFilter"'),'Products page provides a current/archived filter.');
assert.ok(app.includes('Archive product')&&app.includes('Restore product'),'Product details expose archive and restore actions.');
assert.ok(migration.includes('ADD COLUMN IF NOT EXISTS archived_at timestamptz'),'Database adds a nullable archive timestamp.');
assert.ok(migration.includes('NEW.archived_at IS NULL'),'Product changes set marketplace listing visibility from archive state.');
assert.ok(migration.includes('archived_at IS NULL'),'Bulk marketplace sync skips archived products.');
assert.ok(migration.includes('SET is_active=false'),'Archiving retains but deactivates existing marketplace listings.');
assert.ok(salesGuard.includes('FOR UPDATE'),'New sales serialize with concurrent archive changes.');
assert.ok(salesGuard.includes('v_archived_at IS NOT NULL'),'Database rejects inserts when the product is archived.');
assert.ok(salesGuard.includes('BEFORE INSERT ON public.sales'),'Every sales write path is guarded centrally.');
console.log('PASS: reversible archive status, active-only selectors, hard-delete protection and Buybook listing visibility.');
